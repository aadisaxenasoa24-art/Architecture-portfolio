ADVANCE = 5.6          # cell widths between glyph origins
HEIGHT = 6.0


def text_polylines(s, x, y, h, angle_deg=0.0, anchor="left"):
    """Return [Nx2 array, ...] for `s` drawn with cap height `h` at (x, y)."""
    k = h / HEIGHT
    s = s.upper()
    width = ADVANCE * k * max(0, len(s) - 1) + 4 * k
    ox = {"left": 0.0, "centre": -width / 2.0, "right": -width}[anchor]
    out = []
    for i, ch in enumerate(s):
        for stroke in _G.get(ch, _G[" "]):
            a = np.asarray(stroke, dtype=float) * k
            a[:, 0] += ox + i * ADVANCE * k
            out.append(a)
    if angle_deg:
        t = np.radians(angle_deg)
        R = np.array([[np.cos(t), -np.sin(t)], [np.sin(t), np.cos(t)]])
        out = [a @ R.T for a in out]
    return [a + np.array([x, y]) for a in out]


def text_width(s, h):
    k = h / HEIGHT
    return ADVANCE * k * max(0, len(s) - 1) + 4 * k
